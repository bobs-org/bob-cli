def _subset_cli_font(repo: Path) -> bytes:
    """Subset bundled JetBrains Mono to a deterministic WOFF2 for SVG-as-image."""

    try:
        import brotli  # noqa: F401
        from fontTools import subset
    except ImportError as error:
        raise DocsError(
            "missing media dependency (fonttools, brotli); run with `uv run --project tools/docs bob-docs media`"
        ) from error
    src = repo / FONT_PATH
    if not src.is_file():
        raise DocsError(f"bundled JetBrains Mono is missing: {src}")
    import tempfile

    with tempfile.TemporaryDirectory(prefix="bob-docs-media-font-") as raw:
        dest = Path(raw) / "cli.woff2"
        options = subset.Options()
        options.flavor = "woff2"
        options.with_zopfli = False
        options.hinting = True
        options.desubroutinize = False
        options.name_IDs = ["*"]
        options.glyph_names = False
        options.recalc_bounds = True
        options.recalc_timestamp = False
        options.prune_unicode = True
        options.prune_name = True
        font = subset.load_font(str(src), options)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=subset.parse_unicodes(FONT_UNICODES))
        subsetter.subset(font)
        if "head" in font:
            font["head"].modified = FONT_TIMESTAMP
        font.save(str(dest))
        return dest.read_bytes()


def font_face_css(repo: Path) -> str:
    payload = base64.b64encode(_subset_cli_font(repo)).decode("ascii")
    return (
        "@font-face {\n"
        f'        font-family: "{FONT_FAMILY}";\n'
        f'        src: url("data:{FONT_MIME};base64,{payload}") format("{FONT_FORMAT}");\n'
        "        font-style: normal;\n"
        "        font-weight: 400;\n"
        "        font-display: block;\n"
        "    }\n"
    )


def media_environment(sandbox: BobSandbox) -> dict[str, str]:
    """Color-capable PTY environment on top of the shared sandbox isolation."""

    env = dict(sandbox.env)
    env.pop("NO_COLOR", None)
    env["TERM"] = TERM
    env["COLUMNS"] = str(COLUMNS)
    env["LINES"] = str(ROWS)
    env["LC_ALL"] = "en_US.UTF-8"
    env["LANG"] = "en_US.UTF-8"
    env["TZ"] = "UTC"
    return env


def _set_winsize(fd: int, rows: int, columns: int) -> None:
    winsize = struct.pack("HHHH", rows, columns, 0, 0)
    fcntl.ioctl(fd, termios.TIOCSWINSZ, winsize)


def _kill_group(proc: subprocess.Popen[bytes]) -> None:
    try:
        os.killpg(proc.pid, signal.SIGTERM)
    except ProcessLookupError:
        return
    try:
        proc.wait(timeout=2)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            return
        proc.wait()


def capture_pty(
    command: list[str],
    *,
    env: Mapping[str, str],
    cwd: Path,
    columns: int = COLUMNS,
    rows: int = ROWS,
    timeout: float = PTY_TIMEOUT_SECONDS,
) -> tuple[int, bytes]:
    """Run ``command`` under a POSIX PTY and return ``(exit_status, raw_bytes)``."""

    try:
        master_fd, slave_fd = pty.openpty()
    except OSError as error:
        raise DocsError(f"could not open a PTY: {error}") from error
    slave_open = True
    try:
        _set_winsize(master_fd, rows, columns)
        _set_winsize(slave_fd, rows, columns)
        try:
            proc = subprocess.Popen(
                command,
                stdin=slave_fd,
                stdout=slave_fd,
                stderr=slave_fd,
                cwd=cwd,
                env=dict(env),
                start_new_session=True,
                close_fds=True,
            )
        except OSError as error:
            raise DocsError(f"could not start {' '.join(command)}: {error}") from error
        os.close(slave_fd)
        slave_open = False
        chunks: list[bytes] = []
        deadline = time.monotonic() + timeout
        timed_out = False
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                timed_out = True
                _kill_group(proc)
                break
            try:
                ready, _, _ = select.select([master_fd], [], [], min(0.25, remaining))
            except (InterruptedError, ValueError):
                ready = []
            if ready:
                try:
                    data = os.read(master_fd, 65536)
                except OSError as error:
                    if error.errno == errno.EIO:
                        break
                    if error.errno in (errno.EAGAIN, errno.EWOULDBLOCK):
                        data = b""
                    else:
                        raise
                else:
                    if not data:
                        break
                    chunks.append(data)
            if proc.poll() is not None:
                while True:
                    try:
                        ready, _, _ = select.select([master_fd], [], [], 0.05)
                    except (InterruptedError, ValueError):
                        break
                    if not ready:
                        break
                    try:
                        data = os.read(master_fd, 65536)
                    except OSError:
                        data = b""
                    if not data:
                        break
                    chunks.append(data)
                break
        status = proc.wait()
        if timed_out:
            raise DocsError(f"{command[0]} timed out after {timeout:g}s under a PTY")
        return status, b"".join(chunks)
    finally:
        if slave_open:
            os.close(slave_fd)
        os.close(master_fd)


def normalize_captured_text(raw: bytes, *, sandbox_root: Path | None = None) -> str:
    """Drop known PTY/transport noise; keep semantic ANSI and text."""

    text = raw.decode("utf-8", "replace")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = text.replace("\x00", "").replace("\x07", "")
    text = _OSC.sub("", text)
    text = _CHARSET.sub("", text)
    text = _CSI_NON_SGR.sub("", text)
    text = _SANDBOX_PATH.sub("/bob-docs-sandbox", text)
    if sandbox_root is not None:
        text = text.replace(str(sandbox_root), "/bob-docs-sandbox")
        text = text.replace(str(sandbox_root.parent), "/tmp")
    return text


def render_svg(
    ansi: str,
    *,
    title: str,
    unique_id: str,
    repo: Path,
    width: int = COLUMNS,
) -> str:
    """Convert captured ANSI into a deterministic, self-contained SVG."""

    _require_rich()
    from rich.console import Console
    from rich.text import Text

    console = Console(
        record=True,
        width=width,
        color_system="truecolor",
        force_terminal=True,
        legacy_windows=False,
        file=io.StringIO(),
    )
    console.print(Text.from_ansi(ansi.rstrip("\n")), end="")
    svg = console.export_svg(
        title=title,
        theme=_bob_theme(),
        clear=True,
        code_format=_svg_format(),
        font_aspect_ratio=FONT_ASPECT_RATIO,
        unique_id=unique_id,
    )
    svg = svg.replace("@@FONT_FACE@@", font_face_css(repo))
    svg = svg.replace("@@TITLE@@", title)
    svg = svg.replace(_RICH_CHROME_STROKE, _CHROME_STROKE)
    if not svg.endswith("\n"):
        svg += "\n"
    return svg


def _select_vault(sandbox: BobSandbox) -> Path:
    vault = sandbox.workdir / "vault"
    if vault.exists():
        raise DocsError(f"media vault path already exists: {vault}")
    shutil.copytree(sandbox.demo_source, vault)
    sandbox.env["BOB_DIR"] = str(vault)
    return vault


def _write_daily_note(sandbox: BobSandbox, vault: Path) -> Path:
    day = sandbox.now[:10]
    daily = vault / day[:4] / f"{day.replace('-', '')}.md"
    daily.parent.mkdir(parents=True, exist_ok=True)
    daily.write_text(f"# Sprout Shed — {day}\n\n## Pomodoros\n", encoding="utf-8")
    sandbox.env["BOB_DAY_FILE"] = str(daily)
    return daily


def _run_bob_plain(sandbox: BobSandbox, args: tuple[str, ...]) -> None:
    try:
        completed = subprocess.run(
            [str(sandbox.bob_bin), *args],
            cwd=sandbox.workdir,
            env=sandbox.env,
            check=False,
            capture_output=True,
            text=True,
            timeout=PTY_TIMEOUT_SECONDS,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise DocsError(f"media setup `bob {' '.join(args)}` failed: {error}") from error
    if completed.returncode:
        detail = (completed.stderr or completed.stdout).strip()
        raise DocsError(
            f"media setup `bob {' '.join(args)}` exited {completed.returncode}: {detail}"
        )


def _run_bob_pty(sandbox: BobSandbox, args: tuple[str, ...]) -> str:
    env = media_environment(sandbox)
    status, raw = capture_pty(
        [str(sandbox.bob_bin), *args],
        env=env,
        cwd=sandbox.workdir,
    )
    text = normalize_captured_text(raw, sandbox_root=sandbox.root)
    if status:
        raise DocsError(
            f"`bob {' '.join(args)}` exited {status} under a PTY; output:\n{text[-2000:]}"
        )
    if "\x1b[" not in text:
        raise DocsError(
            f"`bob {' '.join(args)}` did not emit ANSI color under the PTY "
            f"(TERM={env.get('TERM')!r}, isatty expected)"
        )
    return text


def _prepare_plan(sandbox: BobSandbox, vault: Path) -> None:
    _run_bob_plain(sandbox, ("capture", "Water the seedlings @garden^seedlings"))
    _write_daily_note(sandbox, vault)
    _run_bob_plain(sandbox, ("capture", "=#focus"))
    _run_bob_plain(sandbox, ("capture", "@garden:seedlings"))


def render_all_shots(
    repo: Path,
    bob_bin: Path,
    *,
    now: str = DEFAULT_NOW,
    source_env: Mapping[str, str] | None = None,
) -> dict[str, str]:
    """Capture every declared shot in one isolated sandbox and return SVG text."""

    rendered: dict[str, str] = {}
    with bob_sandbox(repo, bob_bin, now=now, source_env=source_env) as sandbox:
        vault = _select_vault(sandbox)
        for shot in SHOTS:
            if shot.name == "plan":
                _prepare_plan(sandbox, vault)
            ansi = _run_bob_pty(sandbox, shot.args)
            rendered[shot.relative_path] = render_svg(
                ansi,
                title=shot.title,
                unique_id=shot.unique_id,
                repo=repo,
            )
    return rendered


def _committed_svg(repo: Path, relative: str) -> bytes | None:
    path = repo / "docs" / relative
    if not path.is_file():
        return None
    return path.read_bytes()


def _write_svgs(repo: Path, rendered: dict[str, str]) -> None:
    for relative, svg in rendered.items():
        path = repo / "docs" / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(svg, encoding="utf-8")
        print(f"media: docs/{relative} {path.stat().st_size} bytes")


def run_media(
    root: Path,
    *,
    check: bool = False,
    bob_bin: Path | None = None,
    now: str = DEFAULT_NOW,
    source_env: Mapping[str, str] | None = None,
) -> int:
    """Generate CLI SVGs, or compare two independent renders with the committed files."""

    repo = Path(root).resolve()
    if bob_bin is None:
        bob_bin = resolve_bob_binary(repo, source_env=source_env)
    first = render_all_shots(repo, bob_bin, now=now, source_env=source_env)
    second = render_all_shots(repo, bob_bin, now=now, source_env=source_env)
    unstable = sorted(path for path, svg in first.items() if second.get(path) != svg)
    if unstable:
        joined = ", ".join(f"docs/{path}" for path in unstable)
        raise DocsError(
            f"media generation is not byte-stable across sandboxes: {joined} "
            f"(regenerate with {REGENERATE_COMMAND})"
        )
    if check:
        drift: list[str] = []
        for relative, svg in first.items():
            committed = _committed_svg(repo, relative)
            if committed is None or committed != svg.encode("utf-8"):
                drift.append(f"docs/{relative}")
        if drift:
            print(
                f"media: drift in {', '.join(drift)} (regenerate with {REGENERATE_COMMAND})"
            )
            return 1
        print("media: check passed (regeneration is byte-stable)")
        return 0
    _write_svgs(repo, first)
    print(f"media: date {GENERATED_DATE}")
    return 0
