    from rich.terminal_theme import TerminalTheme

    # Map ANSI onto the notebook tokens in docs/stylesheets/bob.css.
    paper = (251, 248, 242)
    ink = (23, 28, 26)
    identity = (10, 147, 145)
    link = (15, 107, 99)
    caution = (129, 24, 43)
    today = (155, 61, 45)
    today_glyph = (217, 71, 43)
    prj = (109, 40, 217)
    muted = (92, 95, 90)
    return TerminalTheme(
        paper,
        ink,
        [ink, caution, identity, today, link, prj, identity, muted],
        [muted, today_glyph, identity, today, link, prj, identity, ink],
    )


