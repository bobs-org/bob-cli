"""Generate the deterministic By component index from guide and concept tags."""

from __future__ import annotations

from pathlib import Path, PurePosixPath

from .errors import DocsError
from .markdown import parse_front_matter

COMPONENT_NAMES = ("CLI", "Obsidian", "macOS")
COMPONENT_ANCHORS = {
    "CLI": "cli",
    "Obsidian": "obsidian",
    "macOS": "macos",
}
SCAN_DIRS = ("guides", "concepts")
INDEX_REL = Path("docs/reference/by-component.md")
ALLOWED_TAGS = frozenset(COMPONENT_NAMES)


def _posix_under_docs(docs: Path, path: Path) -> str:
    return path.resolve().relative_to(docs.resolve()).as_posix()


def _is_hub(path: Path) -> bool:
    return path.name == "index.md"


def _iter_authored_pages(docs: Path) -> list[Path]:
    pages: list[Path] = []
    docs_root = docs.resolve()
    for folder in SCAN_DIRS:
        root = docs / folder
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*.md")):
            if not path.is_file() or path.is_symlink():
                continue
            resolved = path.resolve()
            if not resolved.is_relative_to(docs_root):
                raise DocsError(f"{path}: page path escapes docs/")
            pages.append(path)
    return pages


def _require_tags(path: Path, tags: object) -> tuple[str, ...]:
    if not isinstance(tags, list) or not tags:
        raise DocsError(
            f"{path}: non-hub guide and concept pages must declare a nonempty "
            "tags list drawn from CLI, Obsidian, macOS"
        )
    seen: list[str] = []
    for tag in tags:
        if not isinstance(tag, str) or not tag.strip():
            raise DocsError(
                f"{path}: each component tag must be a nonempty string from "
                "CLI, Obsidian, macOS"
            )
        if tag not in ALLOWED_TAGS:
            raise DocsError(
                f"{path}: unknown component tag {tag!r}; allowed: "
                + ", ".join(COMPONENT_NAMES)
            )
        if tag not in seen:
            seen.append(tag)
    return tuple(seen)


def collect_component_pages(docs: Path) -> dict[str, list[tuple[str, str]]]:
    """Return component membership as (title, docs-relative path) lists."""

    groups = {name: [] for name in COMPONENT_NAMES}
    for path in _iter_authored_pages(docs):
        if _is_hub(path):
            continue
        text = path.read_text(encoding="utf-8")
        source = str(path)
        head, _body, error = parse_front_matter(text, source=source)
        if error:
            raise DocsError(error)
        if head is None:
            raise DocsError(
                f"{path}: non-hub guide and concept pages must declare front matter "
                "with a nonempty tags list drawn from CLI, Obsidian, macOS"
            )
        title = head.get("title")
        if not isinstance(title, str) or not title.strip():
            raise DocsError(f"{path}: missing front matter key 'title' (must be a string)")
        tags = _require_tags(path, head.get("tags"))
        rel = _posix_under_docs(docs, path)
        entry = (title.strip(), rel)
        for tag in tags:
            groups[tag].append(entry)
    for name, entries in groups.items():
        groups[name] = sorted(entries, key=lambda item: (item[0].casefold(), item[1]))
    return groups


def _relative_link(page_rel: str) -> str:
    return PurePosixPath(os_relpath(page_rel, "reference")).as_posix()


def os_relpath(target: str, start: str) -> str:
    """Return a POSIX relative path from ``start`` to ``target``."""

    start_parts = PurePosixPath(start).parts
    target_path = PurePosixPath(target)
    target_parts = target_path.parts
    common = 0
    for left, right in zip(start_parts, target_parts, strict=False):
        if left != right:
            break
        common += 1
    ups = [".."] * (len(start_parts) - common)
    rest = target_parts[common:]
    if not ups and not rest:
        return "."
    return str(PurePosixPath(*ups, *rest))


def render_component_index(groups: dict[str, list[tuple[str, str]]]) -> str:
    """Render the complete generated By component page."""

    lines = [
        "---",
        "title: By component",
        "description: Find guides and concepts tagged CLI, Obsidian, or macOS.",
        "---",
        "<!-- generated by bob-docs; run just docs-gen -->",
        "",
        "# By component",
        "",
        "Guides and concepts grouped by the Bob surface they use. A page that",
        "uses more than one surface appears in each matching group.",
        "",
    ]
    for name in COMPONENT_NAMES:
        anchor = COMPONENT_ANCHORS[name]
        lines.extend((f"## {name} {{#{anchor}}}", ""))
        entries = groups[name]
        if entries:
            for title, rel in entries:
                lines.append(f"- [{title}]({_relative_link(rel)})")
        else:
            lines.append("No tagged pages yet.")
        lines.append("")
    lines.extend(
        (
            "## Related",
            "",
            "- [Guides](../guides/index.md)",
            "- [Understand Bob](../concepts/index.md)",
            "",
        )
    )
    return "\n".join(lines)


def generate_components(root: Path, *, check: bool = False) -> list[Path]:
    """Generate the component index; with check=True, report but do not write drift."""

    docs = root / "docs"
    groups = collect_component_pages(docs)
    desired = render_component_index(groups)
    path = root / INDEX_REL
    try:
        current = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        current = None
    if current == desired:
        return []
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(desired, encoding="utf-8")
    return [path]
