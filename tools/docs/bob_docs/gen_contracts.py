"""Generate the in-place contract index, nav, and README table."""

from __future__ import annotations

import json
from pathlib import Path

from .contracts import Contract, ContractGroup, ContractRegistry, load_contract_registry
from .errors import DocsError
from .gen_components import generate_components
from .gen_plugins import run_plugin_inventory
from .gen_reference import generate_reference
from .generated import first_heading, replace_generated_region


def _readme_table(registry: ContractRegistry) -> str:
    lines = ["| Guide | What it covers |", "| --- | --- |"]
    for entry in registry.entries:
        lines.append(f"| [{entry.stem}.md]({entry.stem}.md) | {entry.summary} |")
    return "\n".join(lines)


def _contract_page(root: Path, entry: Contract) -> str:
    page = root / "docs" / f"{entry.stem}.md"
    title = first_heading(page.read_text(encoding="utf-8"))
    historical = " (historical)" if entry.historical else ""
    return f"- [{title}{historical}](../{entry.stem}.md) — {entry.summary}"


def _contracts_markdown(root: Path, registry: ContractRegistry) -> str:
    lines = [
        "---",
        "title: Contracts",
        "description: Bob behavior contracts and conformance specifications.",
        "---",
        "<!-- generated by bob-docs; run just docs-gen -->",
        "",
        "# Contracts",
        "",
        "These pages specify behavior that Bob components and their tests must agree on.",
        "",
    ]
    for group in registry.groups:
        lines.extend((f"## {group.title}", ""))
        for entry in sorted(group.entries, key=lambda item: item.order):
            lines.append(_contract_page(root, entry))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _nav_block(root: Path, registry: ContractRegistry) -> str:
    lines: list[str] = []
    for group in registry.groups:
        lines.append(f"          - {json.dumps(group.title, ensure_ascii=False)}:")
        for entry in sorted(group.entries, key=lambda item: item.order):
            title = first_heading(
                (root / "docs" / f"{entry.stem}.md").read_text(encoding="utf-8")
            )
            if entry.historical:
                title += " (historical)"
            lines.append(
                f"              - {json.dumps(title, ensure_ascii=False)}: {entry.stem}.md"
            )
    return "\n".join(lines)


def generate_contracts(root: Path, *, check: bool = False) -> list[Path]:
    """Generate deterministic outputs; with check=True, report but do not write drift."""

    registry = load_contract_registry(root)
    readme_path = root / "docs/README.md"
    config_path = root / "mkdocs.yml"
    generated_page_path = root / "docs/develop/contracts.md"
    desired_readme = replace_generated_region(
        readme_path.read_text(encoding="utf-8"),
        "contract table",
        _readme_table(registry),
    )
    desired_config = replace_generated_region(
        config_path.read_text(encoding="utf-8"),
        "contracts nav",
        _nav_block(root, registry),
        yaml=True,
    )
    desired_page = _contracts_markdown(root, registry)

    desired = {
        readme_path: desired_readme,
        config_path: desired_config,
        generated_page_path: desired_page,
    }
    drift: list[Path] = []
    for path, content in desired.items():
        try:
            current = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = None
        if current != content:
            drift.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    return drift


def check_or_generate(
    root: Path,
    *,
    check: bool,
    source_dirs: dict[str, Path] | None = None,
    production: bool = False,
) -> int:
    drift = generate_contracts(root, check=check)
    drift.extend(generate_reference(root, check=check))
    drift.extend(generate_components(root, check=check))
    plugin_status = run_plugin_inventory(
        root, check=check, source_dirs=source_dirs, production=production
    )
    status = 0
    if check and drift:
        for path in drift:
            print(f"out of date: {path.relative_to(root)} (run just docs-gen)")
        status = 1
    elif not check:
        for path in drift:
            print(f"generated: {path.relative_to(root)}")
    elif not drift:
        print("generated contract content is up to date")
    if plugin_status:
        return plugin_status
    return status
