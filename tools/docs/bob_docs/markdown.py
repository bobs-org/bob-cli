"""Line-preserving Markdown helpers for the documentation contract lint."""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Iterator

from .errors import DocsError
from .yaml_tools import load_yaml_text

FENCE_OPEN_RE = re.compile(r"(?m)^([ \t]{0,3})(`{3,}|~{3,})([^\n]*)\n")
HTML_COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
GENERATED_BLOCK_RE = re.compile(
    r"(?:<!--\s*)?BEGIN GENERATED.*?END GENERATED(?:\s*-->)?",
    re.DOTALL | re.IGNORECASE,
)
WHOLE_FILE_GENERATED_RE = re.compile(
    r"<!--\s*generated by \S+; run just docs-gen\s*-->",
    re.IGNORECASE,
)
INLINE_CODE_RE = re.compile(r"`[^`\n]+`")
INLINE_LINK_DEST_RE = re.compile(
    r"\]\((?:<[^>\n]*>|[^\s)]+)(?:\s+(?:\"[^\n\"]*\"|'[^\n']*'|\([^\n)]*\)))?\)"
)
REF_LINK_DEF_RE = re.compile(r"(?m)^(\s{0,3}\[[^\]\n]+\]:)[^\n]*$")
HTML_MEDIA_ATTR_RE = re.compile(
    r"(\b(?:src|href|poster)\s*=\s*)(?:\"[^\"]*\"|'[^']*'|[^\s>]+)",
    re.IGNORECASE,
)
WORD_RE = re.compile(r"\S+")


@dataclass(frozen=True)
class Fence:
    """One fenced code block, with source offsets and 1-indexed line numbers."""

    start: int
    end: int
    start_line: int
    info: str
    body: str
    body_start: int


def line_at(text: str, offset: int) -> int:
    """Return the 1-indexed line number of ``offset`` in ``text``."""

    if offset < 0:
        return 1
    return text.count("\n", 0, min(offset, len(text))) + 1


def split_front_matter(text: str) -> tuple[str | None, str, int]:
    """Return (front matter text, body, body start offset)."""

    if not text.startswith("---\n"):
        return None, text, 0
    rest = text[4:]
    for opener_close, length in (("---\n", 4), ("...\n", 4), ("---", 3), ("...", 3)):
        if rest == opener_close.rstrip("\n") or rest.startswith(opener_close):
            body_start = 4 + length if rest.startswith(opener_close) else len(text)
            if rest == opener_close.rstrip("\n"):
                return "", "", len(text)
            return "", text[body_start:], body_start
    candidates: list[tuple[int, int]] = []
    for closer in ("\n---\n", "\n---", "\n...\n", "\n..."):
        index = rest.find(closer)
        if index != -1:
            candidates.append((index, len(closer)))
    if not candidates:
        return None, text, 0
    index, length = min(candidates, key=lambda item: (item[0], -item[1]))
    body_start = 4 + index + length
    return rest[:index], text[body_start:], body_start


def parse_front_matter(text: str, *, source: str) -> tuple[dict[str, object] | None, str, str | None]:
    """Parse YAML front matter.

    Returns ``(mapping or None, body, error)``. A missing front matter block is
    ``(None, text, None)``. Malformed YAML is ``({}, body, error)``.
    """

    raw, body, _ = split_front_matter(text)
    if raw is None:
        return None, text, None
    try:
        loaded = load_yaml_text(raw, source=source)
    except DocsError as error:
        return {}, body, str(error)
    if loaded is None:
        return {}, body, None
    if not isinstance(loaded, dict) or not all(isinstance(key, str) for key in loaded):
        return {}, body, f"{source}: front matter must be a mapping"
    return loaded, body, None


def iter_fences(text: str) -> Iterator[Fence]:
    """Yield fenced code blocks without disturbing surrounding line numbers."""

    pos = 0
    while True:
        match = FENCE_OPEN_RE.search(text, pos)
        if not match:
            return
        indent, ticks, info = match.group(1), match.group(2), match.group(3)
        closer = re.compile(
            rf"(?m)^{re.escape(indent)}{re.escape(ticks[0] * len(ticks))}[ \t]*$",
        )
        rest = text[match.end() :]
        close = closer.search(rest)
        if close is None:
            end = len(text)
            body = rest
            body_start = match.end()
        else:
            body = rest[: close.start()]
            body_start = match.end()
            end = match.end() + close.end()
        yield Fence(
            start=match.start(),
            end=end,
            start_line=line_at(text, match.start()),
            info=info.strip(),
            body=body,
            body_start=body_start,
        )
        pos = end


def fence_language(info: str) -> str:
    """Return the fence language token, ignoring classes and titles."""

    if not info:
        return ""
    token = info.split()[0]
    if token.startswith(".") or token.startswith("title="):
        return ""
    return token


def mask_spans(text: str, spans: list[tuple[int, int]]) -> str:
    """Blank non-newline characters in ``spans`` so line numbers stay put."""

    if not spans:
        return text
    chars = list(text)
    for start, end in spans:
        lo = max(0, start)
        hi = min(len(chars), end)
        for index in range(lo, hi):
            if chars[index] != "\n":
                chars[index] = " "
    return "".join(chars)


def _comment_and_generated_spans(text: str) -> list[tuple[int, int]]:
    spans = [(match.start(), match.end()) for match in HTML_COMMENT_RE.finditer(text)]
    spans.extend((match.start(), match.end()) for match in GENERATED_BLOCK_RE.finditer(text))
    return spans


def mask_comments_and_generated(text: str) -> str:
    return mask_spans(text, _comment_and_generated_spans(text))


def mask_code(text: str) -> str:
    """Mask fenced and inline code while preserving line positions."""

    spans = [(fence.start, fence.end) for fence in iter_fences(text)]
    spans.extend((match.start(), match.end()) for match in INLINE_CODE_RE.finditer(text))
    return mask_spans(text, spans)


def mask_for_hygiene(text: str) -> str:
    """Mask front matter, comments, generated blocks, and code for hygiene scans."""

    raw, _, body_start = split_front_matter(text)
    spans: list[tuple[int, int]] = []
    if raw is not None:
        spans.append((0, body_start))
    spans.extend(_comment_and_generated_spans(text))
    spans.extend((fence.start, fence.end) for fence in iter_fences(text))
    spans.extend((match.start(), match.end()) for match in INLINE_CODE_RE.finditer(text))
    return mask_spans(text, spans)


def blank_link_destinations(text: str) -> str:
    """Blank Markdown and HTML destinations so hygiene skips filenames."""

    text = INLINE_LINK_DEST_RE.sub("]()", text)
    text = REF_LINK_DEF_RE.sub(r"\1", text)
    return HTML_MEDIA_ATTR_RE.sub(r'\1""', text)


def is_whole_file_generated(text: str) -> bool:
    """Whether the first body line is the whole-page generated marker."""

    _, body, _ = split_front_matter(text)
    for line in body.splitlines():
        if not line.strip():
            continue
        return bool(WHOLE_FILE_GENERATED_RE.fullmatch(line.strip()))
    return False


def count_words(text: str) -> int:
    """Count words outside front matter, fences, comments, and generated blocks."""

    _, body, _ = split_front_matter(text)
    masked = mask_comments_and_generated(body)
    masked = mask_spans(masked, [(fence.start, fence.end) for fence in iter_fences(masked)])
    return len(WORD_RE.findall(masked))
