ROOT = Path(__file__).resolve().parents[3]
GREEN = "\x1b[32;1mok\x1b[0m captured  mac_inbox.md\n  - [ ] #task Review the queue input\n"


def test_normalize_keeps_ansi_and_strips_sandbox_paths_and_pty_noise() -> None:
    raw = (
        b"\x1b[?2004h\x1b[?1034h\r\n\x1b[32;1mok\x1b[0m captured  "
        b"/tmp/bob-docs-sandbox-abc123/vault/mac_inbox.md\r\n"
        b"\x1b]0;bob\x07"
    )
    text = normalize_captured_text(raw, sandbox_root=Path("/tmp/bob-docs-sandbox-abc123"))
    assert "\x1b[32;1mok\x1b[0m" in text
    assert "/bob-docs-sandbox/vault/mac_inbox.md" in text
    assert "?2004h" not in text
    assert "?1034h" not in text
    assert "\r" not in text


def test_svg_generation_is_stable_embeds_font_and_preserves_color() -> None:
    first = render_svg(GREEN, title="bob capture", unique_id="bob-cli-capture", repo=ROOT)
    second = render_svg(GREEN, title="bob capture", unique_id="bob-cli-capture", repo=ROOT)
    assert first == second
    assert first.endswith("\n")
    assert 'id="bob-cli-capture-clip-terminal"' in first
    assert "data:font/woff2;base64," in first
    assert "cdnjs" not in first and "fonts.google" not in first
    assert "#0A9391" in first.upper() or "#0a9391" in first
    assert "Generated by bob-docs media" in first
    assert "<title>bob capture</title>" in first


def test_pty_preserves_ansi_and_reports_nonzero_status() -> None:
    env = dict(os.environ)
    env["TERM"] = "xterm-256color"
    status, raw = capture_pty(
        [
            "python3",
            "-c",
            "import sys; sys.stdout.write('\\x1b[32;1mgreen\\x1b[0m\\n'); sys.stdout.flush()",
        ],
        env=env,
        cwd=ROOT,
        timeout=10,
    )
    assert status == 0
    text = normalize_captured_text(raw)
    assert "\x1b[32;1mgreen\x1b[0m" in text

    failed, _ = capture_pty(
        ["python3", "-c", "import sys; sys.exit(7)"],
        env=env,
        cwd=ROOT,
        timeout=10,
    )
    assert failed == 7


def test_pty_timeout_reaps_the_child() -> None:
    with pytest.raises(DocsError, match="timed out"):
        capture_pty(
            ["python3", "-c", "import time; time.sleep(20)"],
            env=dict(os.environ),
            cwd=ROOT,
            timeout=0.2,
        )


def test_media_environment_enables_color(tmp_path: Path) -> None:
    from bob_docs.sandbox import BobSandbox

    env = isolated_environment(
        root=tmp_path / "sandbox",
        bob_bin=Path("/isolated/bin/bob"),
        now=DEFAULT_NOW,
        source_env={"PATH": "/bin", "NO_COLOR": "1"},
    )
    sandbox = BobSandbox(
        tmp_path / "sandbox",
        tmp_path / "sandbox" / "work",
        Path(env["HOME"]),
        Path(env["BOB_DIR"]),
        tmp_path,
        env,
        Path("/isolated/bin/bob"),
        DEFAULT_NOW,
    )
    colored = media_environment(sandbox)
    assert "NO_COLOR" not in colored
    assert colored["TERM"] == "xterm-256color"
    assert colored["COLUMNS"] == "80"


def test_check_does_not_write_tracked_files(tmp_path: Path, monkeypatch) -> None:
    repo = tmp_path
    target = repo / "docs/assets/media/cli"
    target.mkdir(parents=True)
    capture = target / "capture.svg"
    plan = target / "plan.svg"
    capture.write_text("CAPTURE\n", encoding="utf-8")
    plan.write_text("PLAN\n", encoding="utf-8")
    media_yml = repo / "docs/_meta/media.yml"
    media_yml.parent.mkdir(parents=True, exist_ok=True)
    media_yml.write_text("assets/media/cli/capture.svg:\n  source: x\n  date: 2026-10-20\n")
    before = {
        capture: capture.read_bytes(),
        plan: plan.read_bytes(),
        media_yml: media_yml.read_bytes(),
    }
    rendered = {
        "assets/media/cli/capture.svg": "CAPTURE\n",
        "assets/media/cli/plan.svg": "PLAN\n",
    }
    monkeypatch.setattr("bob_docs.media.resolve_bob_binary", lambda *args, **kwargs: Path("/bin/true"))
    monkeypatch.setattr("bob_docs.media.render_all_shots", lambda *args, **kwargs: dict(rendered))
    assert run_media(repo, check=True) == 0
    for path, payload in before.items():
        assert path.read_bytes() == payload


def test_check_reports_drift_path_and_regeneration_command(tmp_path: Path, monkeypatch, capsys) -> None:
    repo = tmp_path
    target = repo / "docs/assets/media/cli"
    target.mkdir(parents=True)
    (target / "capture.svg").write_text("OLD\n", encoding="utf-8")
    (target / "plan.svg").write_text("PLAN\n", encoding="utf-8")
    rendered = {
        "assets/media/cli/capture.svg": "NEW\n",
        "assets/media/cli/plan.svg": "PLAN\n",
    }
    monkeypatch.setattr("bob_docs.media.resolve_bob_binary", lambda *args, **kwargs: Path("/bin/true"))
    monkeypatch.setattr("bob_docs.media.render_all_shots", lambda *args, **kwargs: dict(rendered))
    assert run_media(repo, check=True) == 1
    output = capsys.readouterr().out
    assert "docs/assets/media/cli/capture.svg" in output
    assert "just docs-media" in output
    assert (target / "capture.svg").read_text(encoding="utf-8") == "OLD\n"


@pytest.fixture(scope="session")
def media_bob_binary() -> Path:
    if "BOB_BIN" not in os.environ and shutil.which("cargo") is None:
        pytest.skip("media integration requires Cargo or BOB_BIN")
    return resolve_bob_binary(ROOT)


@pytest.mark.integration
def test_declared_shots_render_from_real_bob(media_bob_binary: Path) -> None:
    rendered = render_all_shots(ROOT, media_bob_binary)
    assert set(rendered) == {shot.relative_path for shot in SHOTS}
    for svg in rendered.values():
        assert "data:font/woff2;base64," in svg
        assert "\x1b[" not in svg
        assert "bob-docs media" in svg
