def test_generate_reference_writes_and_detects_drift(tmp_path: Path) -> None:
    memory = tmp_path / "sase" / "memory"
    memory.mkdir(parents=True, exist_ok=True)
    (memory / "glossary.md").write_text("# Glossary Terms\n", encoding="utf-8")
    (memory / "decisions.md").write_text("# Decisions\n", encoding="utf-8")
    write_strand(
        memory / "glossary", "term", "keyword: Term\n", "See [[decisions:rule]].\n"
    )
    write_strand(
        memory / "decisions",
        "rule",
        "keyword: Rule\nsummary: The rule.\nmetadata:\n  status: accepted\n",
        "See [[glossary:term]].\n",
    )
    drift = generate_reference(tmp_path)
    assert {path.name for path in drift} == {"glossary.md", "decisions.md"}
    assert not generate_reference(tmp_path, check=True)
    glossary = tmp_path / "docs" / "reference" / "glossary.md"
    glossary.write_text(glossary.read_text(encoding="utf-8") + "drift\n", encoding="utf-8")
    assert generate_reference(tmp_path, check=True) == [glossary]
