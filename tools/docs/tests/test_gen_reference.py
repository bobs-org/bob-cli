"""Unit tests for memory-web reference page generation."""

from pathlib import Path

import pytest

from bob_docs.errors import DocsError
from bob_docs.gen_reference import (
    check_no_bead_ids,
    convert_wiki_links,
    generate_reference,
    load_strands,
    render_decisions_page,
    render_glossary_page,
    resolve_wiki_link,
)


def write_strand(directory: Path, stem: str, front: str, body: str) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / f"{stem}.md").write_text(
        f"---\n{front}---\n\n{body}", encoding="utf-8"
    )


@pytest.fixture()
def webs(tmp_path: Path) -> dict[str, dict[str, object]]:
    memory = tmp_path / "memory"
    memory.mkdir(parents=True, exist_ok=True)
    (memory / "glossary.md").write_text("# Glossary Terms\n", encoding="utf-8")
    (memory / "decisions.md").write_text("# Decisions\n", encoding="utf-8")
    glossary = memory / "glossary"
    decisions = memory / "decisions"
    write_strand(
        glossary,
        "task-link",
        "keyword: Task Link\naliases:\n  - task block link\n",
        "A block link to an Obsidian task. See [[task-dependency-link]] and\n"
        "[[decisions:task-deps-are-depends-on-links]]. `[[task-link]]` stays literal.\n"
        "\n```text\n[[task-link]] in fences stays literal.\n```\n",
    )
    write_strand(
        glossary,
        "task-dependency-link",
        "keyword: Task Dependency Link\n",
        "A task link on a Depends-On line.\n",
    )
    write_strand(
        decisions,
        "task-deps-are-depends-on-links",
        "keyword: Task Dependencies Are Links\nsummary: Links carry deps.\n"
        "metadata:\n  status: accepted\n",
        "**Applies to.** bob-cli. See [[glossary:task-link]].\n",
    )
    return {
        "glossary": {strand.slug: strand for strand in load_strands(tmp_path / "memory", "glossary")},
        "decisions": {strand.slug: strand for strand in load_strands(tmp_path / "memory", "decisions")},
    }


def test_glossary_page_sorts_terms_and_links_anchors(webs: dict) -> None:
    page = render_glossary_page(
        list(webs["glossary"].values()), webs  # type: ignore[arg-type]
    )
    assert "<!-- generated by bob-docs; run just docs-gen -->" in page.splitlines()[4]
    task_link = page.index("### Task Dependency Link {#task-dependency-link}")
    task = page.index("### Task Link {#task-link}")
    assert task_link < task
    assert "*Aliases: task block link.*" in page
    assert "[Task Dependency Link](#task-dependency-link)" in page
    assert "[Task Dependencies Are Links](../develop/decisions.md#task-deps-are-depends-on-links)" in page
    # Inline code and fenced code are never linkified.
    assert "`[[task-link]]` stays literal." in page
    assert "[[task-link]] in fences stays literal." in page


def test_glossary_bare_unknown_links_stay_literal(webs: dict) -> None:
    assert (
        convert_wiki_links("See [[area]] today.", page="glossary", webs=webs)
        == "See [[area]] today."
    )


def test_explicit_cross_web_links_must_resolve(webs: dict) -> None:
    with pytest.raises(DocsError):
        resolve_wiki_link("decisions:no-such-record", page="glossary", webs=webs)
    with pytest.raises(DocsError):
        resolve_wiki_link("glossary:no-such-term", page="decisions", webs=webs)


def test_glossary_generation_fails_on_bead_ids() -> None:
    with pytest.raises(DocsError):
        check_no_bead_ids("see bob-cli-9x for details", path="reference/glossary.md")
    # Code spans are masked before the scan, matching the hygiene gate.
    check_no_bead_ids("see `bob-cli-9x` for details", path="reference/glossary.md")


def test_decisions_page_renders_status_chips(webs: dict) -> None:
    decisions_dir = webs["decisions"]["task-deps-are-depends-on-links"]
    _ = decisions_dir
    page = render_decisions_page(
        list(webs["decisions"].values()), webs  # type: ignore[arg-type]
    )
    assert "## Task Dependencies Are Links {#task-deps-are-depends-on-links}" in page
    assert "**Status:** Accepted" in page
    assert "Links carry deps." in page
    assert "[Task Link](../reference/glossary.md#task-link)" in page


def test_decisions_superseded_links_successors(tmp_path: Path) -> None:
    directory = tmp_path / "memory" / "decisions"
    write_strand(
        directory,
        "old-rule",
        "keyword: Old Rule\nsummary: The old way.\n"
        "metadata:\n  status: superseded\n  superseded_by:\n    - decisions:new-rule\n",
        "Body.\n",
    )
    write_strand(
        directory,
        "new-rule",
        "keyword: New Rule\nsummary: The new way.\nmetadata:\n  status: accepted\n",
        "Body.\n",
    )
    memory = tmp_path / "memory"
    memory.mkdir(parents=True, exist_ok=True)
    (memory / "glossary.md").write_text("# Glossary Terms\n", encoding="utf-8")
    (memory / "decisions.md").write_text("# Decisions\n", encoding="utf-8")
    (memory / "glossary").mkdir(parents=True)
    write_strand(memory / "glossary", "term", "keyword: Term\n", "Body.\n")
    strands = load_strands(tmp_path / "memory", "decisions")
    webs = {
        "glossary": {s.slug: s for s in load_strands(tmp_path / "memory", "glossary")},
        "decisions": {s.slug: s for s in strands},
    }
    page = render_decisions_page(strands, webs)
    assert "**Status:** Superseded by [New Rule](#new-rule)" in page


