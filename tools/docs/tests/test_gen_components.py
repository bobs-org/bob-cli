"""Component index generation against temporary document trees."""

from __future__ import annotations

from pathlib import Path

import pytest

from bob_docs.errors import DocsError
from bob_docs.gen_components import (
    collect_component_pages,
    generate_components,
    render_component_index,
)
from bob_docs.gen_contracts import check_or_generate


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _page(title: str, tags: str, body: str = "Body.\n") -> str:
    return (
        f"---\ntitle: {title}\ndescription: A fixture page.\ntags:\n{tags}---\n\n"
        f"# {title}\n\n{body}"
    )


def _tree(root: Path) -> Path:
    docs = root / "docs"
    _write(
        docs / "guides/index.md",
        "---\ntitle: Guides\ndescription: Hub.\n---\n\n# Guides\n",
    )
    _write(
        docs / "concepts/index.md",
        "---\ntitle: Concepts\ndescription: Hub.\n---\n\n# Concepts\n",
    )
    _write(
        docs / "guides/zebra.md",
        _page("Zebra task", "  - CLI\n  - Obsidian\n"),
    )
    _write(
        docs / "guides/alpha.md",
        _page("Alpha vault", "  - CLI\n  - CLI\n"),
    )
    _write(
        docs / "concepts/mac-panel.md",
        _page("Mac panel", "  - macOS\n  - CLI\n"),
    )
    return docs


def test_membership_order_duplicates_and_hub_exclusion(tmp_path: Path) -> None:
    docs = _tree(tmp_path)
    groups = collect_component_pages(docs)
    assert [title for title, _rel in groups["CLI"]] == ["Alpha vault", "Mac panel", "Zebra task"]
    assert [rel for _title, rel in groups["CLI"]] == [
        "guides/alpha.md",
        "concepts/mac-panel.md",
        "guides/zebra.md",
    ]
    assert groups["Obsidian"] == [("Zebra task", "guides/zebra.md")]
    assert groups["macOS"] == [("Mac panel", "concepts/mac-panel.md")]
    rendered = render_component_index(groups)
    assert "<!-- generated by bob-docs; run just docs-gen -->" in rendered.splitlines()[4]
    assert "## CLI {#cli}" in rendered
    assert "## Obsidian {#obsidian}" in rendered
    assert "## macOS {#macos}" in rendered
    assert "[Alpha vault](../guides/alpha.md)" in rendered
    assert "[Mac panel](../concepts/mac-panel.md)" in rendered
    assert rendered.count("[Alpha vault]") == 1
    assert "guides/index.md" in rendered
    assert "concepts/index.md" in rendered
    assert "guides/index.md" not in rendered.split("## Related", 1)[0]


def test_missing_and_unknown_tags_fail_with_source_path(tmp_path: Path) -> None:
    docs = tmp_path / "docs"
    missing = _write(
        docs / "guides/missing.md",
        "---\ntitle: Missing\ndescription: No tags.\n---\n\n# Missing\n",
    )
    with pytest.raises(DocsError, match=rf"{missing}.*nonempty tags list"):
        collect_component_pages(docs)

    unknown = _write(
        docs / "guides/missing.md",
        _page("Unknown", "  - Windows\n"),
    )
    with pytest.raises(DocsError, match=rf"{unknown}.*unknown component tag 'Windows'"):
        collect_component_pages(docs)

    empty = _write(
        docs / "guides/missing.md",
        "---\ntitle: Empty\ndescription: Empty tags.\ntags: []\n---\n\n# Empty\n",
    )
    with pytest.raises(DocsError, match=rf"{empty}.*nonempty tags list"):
        collect_component_pages(docs)


def test_check_mode_reports_drift_then_write_succeeds(tmp_path: Path) -> None:
    _tree(tmp_path)
    index = tmp_path / "docs/reference/by-component.md"
    _write(index, "# stale\n")
    drifted = generate_components(tmp_path, check=True)
    assert drifted == [index]
    assert index.read_text(encoding="utf-8") == "# stale\n"
    written = generate_components(tmp_path, check=False)
    assert written == [index]
    assert "<!-- generated by bob-docs; run just docs-gen -->" in index.read_text(encoding="utf-8")
    assert generate_components(tmp_path, check=True) == []


def test_check_or_generate_includes_component_index_drift(tmp_path: Path, capsys) -> None:
    _tree(tmp_path)
    _write(
        tmp_path / "docs/_meta/contracts.yml",
        "groups:\n  - title: Group\n    entries:\n"
        "      - stem: alpha\n        summary: Alpha\n        order: 1\n",
    )
    _write(tmp_path / "docs/alpha.md", "# Alpha\n")
    _write(
        tmp_path / "mkdocs.yml",
        "site_name: Fixture\nnav:\n  - Home: index.md\n"
        "  # BEGIN GENERATED: contracts nav\n"
        "  # END GENERATED: contracts nav\n",
    )
    _write(tmp_path / "docs/index.md", "# Home\n")
    _write(tmp_path / "docs/README.md", "<!-- BEGIN GENERATED: contract table -->\n<!-- END GENERATED: contract table -->\n")
    _write(tmp_path / "docs/develop/contracts.md", "# Contracts\n")
    _write(tmp_path / "docs/_meta/mounts.yml", "[]\n")
    _write(tmp_path / "sase/memory/glossary.md", "# Glossary Terms\n")
    _write(tmp_path / "sase/memory/decisions.md", "# Decisions\n")
    _write(
        tmp_path / "sase/memory/glossary/term.md",
        "---\nkeyword: Term\n---\n\nA glossary term.\n",
    )
    _write(
        tmp_path / "sase/memory/decisions/choice.md",
        "---\nkeyword: Choice\nsummary: A fixture decision.\n"
        "metadata:\n  status: accepted\n---\n\n**Claim.** Fixture body.\n",
    )

    status = check_or_generate(tmp_path, check=True)
    out = capsys.readouterr().out
    assert status == 1
    assert "out of date: docs/reference/by-component.md" in out
    assert not (tmp_path / "docs/reference/by-component.md").exists()
    assert check_or_generate(tmp_path, check=False) == 0
    assert (tmp_path / "docs/reference/by-component.md").is_file()
    assert check_or_generate(tmp_path, check=True) == 0
